const fs = require('fs');
const path = require('path');

const SRC_DIR = path.join(__dirname, '../src');
const OUTPUT_FILE = path.join(SRC_DIR, 'app/uxdsl-entry.uxdsl');
const EXCLUDED_FILES = ['uxdsl-entry.uxdsl'];

// The theme is not imported here: `uxdsl build` emits every token (foundations, typography,
// densities, borders, radii, shadows, surfaces, buttons, inputs) once, from the theme JSON
// (uxdsl.theme.cjs). The eleven former `theme/default-*` imports this used to
// list defined every token a second time; those files no longer exist. The color collection
// they alone contributed lives in uxdsl.theme.shared.json, and the `.ds-typo` selector rules
// in app/typography-roles.uxdsl.

// Imported first, in this order, before every other file (alphabetically). The
// `.ds-typo` selector rules lead because the legacy theme import that used to
// carry them led the entry; keeping them first keeps the cascade order the
// site was built with.
const PRIORITY_FILES = [
    'app/typography-roles.uxdsl',
    'app/theme-def.uxdsl',
    'app/layout.uxdsl',
    'app/app.uxdsl'
];

function findFiles(dir, extension, fileList = []) {
  const files = fs.readdirSync(dir);
  files.forEach(file => {
    const filePath = path.join(dir, file);
    if (fs.statSync(filePath).isDirectory()) {
      findFiles(filePath, extension, fileList);
    } else if (filePath.endsWith(extension)) {
      fileList.push(filePath);
    }
  });
  return fileList;
}

function generateEntryFile() {
  console.log('Scanning for .uxdsl files...');
  const allUxdslFiles = findFiles(SRC_DIR, '.uxdsl');
  
  const validFiles = allUxdslFiles.filter(file => {
    return !EXCLUDED_FILES.includes(path.basename(file));
  });

  const outputDir = path.dirname(OUTPUT_FILE);
  
  const importLines = validFiles.map(file => {
      let relPath = path.relative(outputDir, file);
      relPath = relPath.split(path.sep).join('/');
      if (!relPath.startsWith('.')) relPath = './' + relPath;
      
      const priority = PRIORITY_FILES.findIndex(p => file.endsWith(p) || file.endsWith(p.split('/').join(path.sep)));
      return { path: relPath, priority: priority === -1 ? PRIORITY_FILES.length : priority };
  });

  importLines.sort((a, b) => {
      if (a.priority !== b.priority) return a.priority - b.priority;
      return a.path.localeCompare(b.path);
  });

  let lines = [];
  lines.push("/* AUTO-GENERATED FILE - DO NOT EDIT MANUALLY */");
  lines.push("/* Generated by scripts/generate-uxdsl-entry.js */");
  lines.push("");
  lines.push("/* --- Application & Component Imports --- */");
  importLines.forEach(item => lines.push("@import '" + item.path + "';"));
  lines.push("");

  fs.writeFileSync(OUTPUT_FILE, lines.join('\n'));
  console.log("Successfully generated " + OUTPUT_FILE + " with " + importLines.length + " imports.");
}

generateEntryFile();
