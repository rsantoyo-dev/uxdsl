#!/usr/bin/env node
'use strict';

// MIG-B7-17 (FEAT-009), phase A: writes docs/architecture/playground-capability-matrix.md,
// the derived list of what UXDSL can do and where the playground shows it. Generated
// from source (scripts/lib/capabilities.js), never edited by hand; `--check` fails when
// the committed file is stale, the same pattern as generate-language-artifacts.js.

const fs = require('node:fs');
const path = require('node:path');
const { ROOT, deriveCapabilities, dogfoodingCounts, manualEvidence } = require('./lib/capabilities');

const OUT = 'docs/architecture/playground-capability-matrix.md';
const KIND_TITLES = {
  directive: 'Directives', function: 'Value functions', 'breakpoint-function': 'Breakpoint functions', family: 'Theme families',
  role: 'Roles', state: 'Interaction states', runtime: 'Runtime API (named in the package docs)', 'cli-command': 'CLI commands',
  'cli-flag': 'CLI flags', 'package-export': 'Package exports', diagnostics: 'Diagnostics',
};

function render() {
  const rows = deriveCapabilities();
  const { knownGaps, dogfoodingBaseline } = manualEvidence();
  const counts = dogfoodingCounts();
  const kinds = Object.keys(KIND_TITLES).filter((kind) => rows.some((r) => r.kind === kind));
  const gaps = rows.filter((r) => !r.met);
  const out = [];
  out.push('# Playground capability matrix', '');
  out.push('<!-- GENERATED by scripts/generate-capability-matrix.js — do not edit. `node scripts/generate-capability-matrix.js` rewrites it; `--check` fails when it is stale. -->', '');
  out.push('What UXDSL can do, **derived** from its own sources (language metadata, theme-family registry, engine defaults, the runtime API the package docs name, the CLI\'s `--help`, the package `exports` map), and where the playground shows each thing. See `docs/features/FEAT-009/MIG-B7-17-playground-referencia.md`.', '');
  out.push('Levels: **live** — executed on the page (compiled `.uxdsl`, a call to the runtime API, output of the real tool); **documented** — example code or prose only; **none** — not mentioned. The detection reads source text, not rendered pages, so it is a **lower bound** on what the playground shows. A capability is a **gap** when its level is below the one it requires (`live` for nearly everything; `documented` for deprecated syntax and CLI-only options). `capability-evidence.json` in the playground records the evidence text cannot find and the gaps accepted for now.', '');
  out.push(`**${rows.length} capabilities · ${rows.length - gaps.length} shown at the level they require · ${gaps.length} gaps.**`, '');
  out.push('| Kind | Capabilities | live | documented | none | gaps |', '| --- | ---: | ---: | ---: | ---: | ---: |');
  for (const kind of kinds) {
    const list = rows.filter((r) => r.kind === kind);
    out.push(`| ${KIND_TITLES[kind]} | ${list.length} | ${list.filter((r) => r.level === 'live').length} | ${list.filter((r) => r.level === 'documented').length} | ${list.filter((r) => r.level === 'none').length} | ${list.filter((r) => !r.met).length} |`);
  }
  out.push('', '## Gaps', '');
  out.push(gaps.length ? gaps.map((r) => `- \`${r.id}\` — ${r.level}, requires ${r.required}${r.note ? ` (${r.note})` : ''}`).join('\n') : '_None._', '');
  out.push(`Recorded as accepted in \`capability-evidence.json\`: ${knownGaps.length}.`, '');
  out.push('## Dogfooding: styling in the playground that bypasses UXDSL', '');
  out.push('Counted on comment-stripped source. **Candidates to classify, not defects**: a `px` or a hex can be an intentional stable value. The baseline may only go down.', '');
  out.push('| Measure | Now | Baseline |', '| --- | ---: | ---: |');
  for (const [name, value] of Object.entries(counts)) out.push(`| ${name} | ${value} | ${(dogfoodingBaseline || {})[name] ?? '—'} |`);
  out.push('');
  for (const kind of kinds) {
    out.push(`## ${KIND_TITLES[kind]}`, '', '| Capability | Requires | Level | Evidence |', '| --- | --- | --- | --- |');
    for (const r of rows.filter((x) => x.kind === kind)) out.push(`| \`${r.name}\` | ${r.required} | ${r.level}${r.met ? '' : ' ⚠'} | ${(r.files || []).map((f) => `\`${f}\``).join(', ') || '—'} |`);
    out.push('');
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

if (require.main === module) {
  const target = path.join(ROOT, OUT);
  const next = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== next) { console.error(`${OUT} is stale. Run: node scripts/generate-capability-matrix.js`); process.exit(1); }
    console.log(`${OUT} is up to date.`);
  } else {
    fs.writeFileSync(target, next);
    console.log(`wrote ${OUT}`);
  }
}

module.exports = { render, OUT };
