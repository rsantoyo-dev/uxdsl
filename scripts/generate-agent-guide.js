#!/usr/bin/env node
'use strict';

// MIG-B7-15 (FEAT-009): the agent guide travels with the package. The root
// AGENTS.md is the only source; `packages/postcss-uxdsl/docs/agent-guide.md`
// is a generated, byte-for-byte copy behind a short header, shipped in the
// npm tarball (`files`) so a consuming project can point its agents at
// `node_modules/postcss-uxdsl/docs/agent-guide.md` — the guide for the version
// it actually has installed — instead of keeping a copy that ages.
//
//   node scripts/generate-agent-guide.js           # write the copy
//   node scripts/generate-agent-guide.js --check   # exit 1 if it drifted
//
// Never edit the copy by hand; `npm test` runs `--check`.

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(ROOT, 'AGENTS.md');
const TARGET = path.join(ROOT, 'packages', 'postcss-uxdsl', 'docs', 'agent-guide.md');

const HEADER = `<!--
  Generated by scripts/generate-agent-guide.js from the repository's AGENTS.md.
  Do not edit: change AGENTS.md and regenerate. Paths below are relative to the
  UXDSL repository (https://github.com/rsantoyo-dev/uxdsl), not to this package.
-->

`;

function render(source = fs.readFileSync(SOURCE, 'utf8')) {
  return HEADER + source;
}

function check(target = TARGET, source) {
  const expected = render(source);
  return fs.existsSync(target) && fs.readFileSync(target, 'utf8') === expected;
}

if (require.main === module) {
  const rel = path.relative(ROOT, TARGET);
  if (process.argv.includes('--check')) {
    if (!check()) {
      console.error(`Generated agent guide drift: ${rel} — run node scripts/generate-agent-guide.js`);
      process.exitCode = 1;
    }
  } else {
    fs.mkdirSync(path.dirname(TARGET), { recursive: true });
    fs.writeFileSync(TARGET, render());
    console.log(`Wrote ${rel}`);
  }
}

module.exports = { render, check, SOURCE, TARGET, HEADER };
